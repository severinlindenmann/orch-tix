// The encrypted outbox (spec §16). A note, recording, paste or picked file that can't be uploaded
// (offline, or a network error) is still encrypted at creation time; this module keeps exactly the
// prepared upload request in IndexedDB and sends it later. No plaintext is ever stored: the record
// is {uuid, key_version, wrapped_dek, enc_meta, ttl, blob (ciphertext), size, created_at, kind}.
//
// Tickets (spec T10) add the kind "ticket-event": {kind, ref, body, size, created_at, uuid} where
// body is exactly the POST /api/tickets/{ref}/events request, already sealed. A voice note recorded
// offline is a file item of its own; its event carries `after_uuid` (the file item's uuid) and is
// held back while that item is still in the queue, so the file always goes first.
//
// TIX on orch-core (Task 9) adds the kind "decision": {kind, uuid, space, ticket: "TIX-n" | null,
// decisionKind, key_version, body, size, created_at}, where body is the sealed enc_body. It is sent
// as POST /api/decisions (decisionRequest); 409 duplicate_uuid counts as sent. Queueing the same
// decision uuid again (a double tap on Send) keeps the one item already queued.
//
// This file is the state machine plus its IndexedDB store and cross-tab lock. It touches no DOM, so
// node tests drive it with a fake store, fetch and timer. outbox-ui.js wires it into the pages.
import { OUTBOX, openDb, withStore } from "./db.js";

export const MAX_ITEMS = 20;
export const MAX_BYTES = 300 * 1024 * 1024;
export const BACKOFF_MIN_MS = 5_000;
export const BACKOFF_MAX_MS = 300_000;
export const LOCK_NAME = "outbox-flush";

// The fields an outbox record may hold; anything else a caller passes (a display name) is dropped.
const FIELDS = ["uuid", "key_version", "wrapped_dek", "enc_meta", "ttl", "blob", "size", "created_at", "kind"];

export class OutboxFullError extends Error {
  constructor() {
    super(`The outbox is full (${MAX_ITEMS} items or ${MAX_BYTES / 1024 / 1024} MiB). Wait until you're back online.`);
    this.name = "OutboxFullError";
  }
}

// The exact request for a queued decision.
export function decisionRequest(it) {
  return { method: "POST", path: "/api/decisions", json: {
    uuid: it.uuid, space: it.space, ticket: it.ticket ?? null, kind: it.decisionKind, key_version: it.key_version,
    enc_body: it.body } };
}

class AlreadyQueued extends Error {
  constructor(seq) { super("already queued"); this.seq = seq; }
}

export function backoffDelay(attempt) {
  return Math.min(BACKOFF_MAX_MS, BACKOFF_MIN_MS * 2 ** Math.max(0, attempt));
}

export function checkLimits(items, size) {
  const total = items.reduce((sum, x) => sum + (x.size || 0), 0);
  if (items.length >= MAX_ITEMS || total + size > MAX_BYTES) throw new OutboxFullError();
}

// {status, code} of one upload attempt -> what the outbox does with the item. status 0 = no answer.
export function classify({ status, code } = {}) {
  if (status === 200 || status === 201) return "done";
  // The uuid is generated by the client, so a retry of a request the server already committed
  // gets 409 duplicate_uuid: the upload happened.
  if (status === 409 && code === "duplicate_uuid") return "done";
  if (status === 401) return "pause";
  if (status >= 400 && status < 500) return "failed";
  return "retry"; // 5xx, no answer, or anything unexpected
}

export function memoryStore() {
  let seq = 0;
  const rows = new Map();
  const copy = (x) => ({ ...x });
  return {
    async all() { return [...rows.values()].sort((a, b) => a.seq - b.seq).map(copy); },
    async add(rec) { seq += 1; rows.set(seq, { ...rec, seq }); return seq; },
    // check(items) then add, atomically: a throwing check adds nothing. Resolves {seq, before}.
    // (No await between the check and the insert, like the IDB transaction.)
    async addChecked(rec, check) {
      const items = [...rows.values()].sort((a, b) => a.seq - b.seq).map(copy);
      check(items);
      seq += 1;
      rows.set(seq, { ...rec, seq });
      return { seq, before: items.length };
    },
    async put(rec) { rows.set(rec.seq, copy(rec)); },
    async get(key) { return rows.has(key) ? copy(rows.get(key)) : undefined; },
    async delete(key) { rows.delete(key); },
    async clear() { rows.clear(); },
  };
}

export function idbStore() {
  return {
    async all() { return (await withStore(OUTBOX, "readonly", (s) => s.getAll())) ?? []; }, // key order = FIFO
    add: (rec) => withStore(OUTBOX, "readwrite", (s) => s.add(rec)),
    // The limit check and the add in one readwrite transaction, so two tabs (or two quick saves)
    // can't both pass the check and overshoot the limits. A throwing check aborts the transaction.
    async addChecked(rec, check) {
      const db = await openDb();
      try {
        return await new Promise((resolve, reject) => {
          const tx = db.transaction(OUTBOX, "readwrite");
          const store = tx.objectStore(OUTBOX);
          let result;
          let failure = null;
          const all = store.getAll();
          all.onsuccess = () => {
            try {
              check(all.result);
            } catch (e) {
              failure = e;
              tx.abort();
              return;
            }
            const req = store.add(rec);
            req.onsuccess = () => { result = { seq: req.result, before: all.result.length }; };
          };
          tx.oncomplete = () => resolve(result);
          tx.onabort = () => reject(failure || tx.error);
        });
      } finally {
        db.close();
      }
    },
    put: (rec) => withStore(OUTBOX, "readwrite", (s) => s.put(rec)),
    get: (key) => withStore(OUTBOX, "readonly", (s) => s.get(key)),
    delete: (key) => withStore(OUTBOX, "readwrite", (s) => s.delete(key)),
    clear: () => withStore(OUTBOX, "readwrite", (s) => s.clear()),
  };
}

// One flusher across every tab of this origin. Resolves with fn()'s result, or undefined when
// another tab holds the lock (that tab is flushing; this one does nothing).
export function browserLock(name = LOCK_NAME) {
  if (typeof navigator !== "undefined" && navigator.locks && typeof navigator.locks.request === "function") {
    return (fn) => navigator.locks.request(name, { ifAvailable: true }, (lock) => (lock ? fn() : undefined));
  }
  return broadcastLease(name);
}

// Fallback without Web Locks: a lease announced on a BroadcastChannel. A tab that heard another
// tab's live lease skips its flush. Two tabs may still race at the same instant; that only costs a
// second POST, which the server answers with 409 duplicate_uuid (counted as done).
const LEASE_MS = 30_000;
function broadcastLease(name) {
  // Real browsers only: under Node (the unit tests, which have no navigator.locks either) a live
  // BroadcastChannel keeps the event loop running forever on versions where it has no unref()
  // (e.g. Node 22).
  if (typeof document === "undefined" || typeof BroadcastChannel === "undefined") return (fn) => fn();
  const me = Math.random().toString(36).slice(2);
  const ch = new BroadcastChannel(`${name}-lease`);
  ch.unref?.();
  let othersUntil = 0;
  ch.onmessage = (e) => {
    const m = e.data || {};
    if (m.id === me) return;
    if (m.type === "held") othersUntil = Date.now() + LEASE_MS;
    if (m.type === "released") othersUntil = 0;
  };
  return async (fn) => {
    if (Date.now() < othersUntil) return undefined;
    ch.postMessage({ type: "held", id: me });
    try {
      return await fn();
    } finally {
      ch.postMessage({ type: "released", id: me });
    }
  };
}

// send(item) -> {status, code}; throwing counts as a network error.
export function createOutbox({
  store, send, lock = (fn) => fn(),
  // Wrapped: the browser's setTimeout throws "Illegal invocation" when called as a method of another object.
  timers = { set: (fn, ms) => setTimeout(fn, ms), clear: (t) => clearTimeout(t) },
  onChange = () => {}, onDrained = () => {}, persist = () => {}, now = () => Date.now(),
}) {
  const st = { paused: false, attempt: 0, timer: null, nextRetryAt: null, running: null, uploaded: 0 };

  const cancelTimer = () => {
    if (st.timer != null) timers.clear(st.timer);
    st.timer = null;
    st.nextRetryAt = null;
  };

  const arm = () => {
    cancelTimer();
    const ms = backoffDelay(st.attempt);
    st.attempt += 1;
    st.nextRetryAt = now() + ms;
    st.timer = timers.set(() => {
      st.timer = null;
      st.nextRetryAt = null;
      return flush();
    }, ms);
  };

  async function attempt(it) {
    try {
      return (await send(it)) || { status: 0 };
    } catch {
      return { status: 0 };
    }
  }

  async function run() {
    if (st.paused) return;
    for (;;) {
      const all = await store.all();
      const queued = new Set(all.map((x) => x.uuid));
      // An event waiting for its voice note stays put while that file item is still queued
      // (pending or failed); anything behind it that doesn't depend on it goes ahead.
      const next = all.find((x) => x.state !== "failed" && !(x.after_uuid && queued.has(x.after_uuid)));
      if (!next) break;
      const res = await attempt(next);
      const outcome = classify(res);
      if (outcome === "done") {
        // A voice note is up: hand its FILE id to the events waiting for it before the file item
        // goes, so nothing is lost in between. send() resolves {status, id} for an upload.
        if (res.id) {
          for (const dep of all.filter((x) => x.after_uuid === next.uuid)) await store.put({ ...dep, after_file: res.id });
        }
        await store.delete(next.seq);
        st.uploaded += 1;
        st.attempt = 0;
        onChange();
      } else if (outcome === "pause") {
        st.paused = true;
        onChange();
        return;
      } else if (outcome === "failed") {
        await store.put({ ...next, state: "failed", error: res.code || `http_${res.status}` });
        onChange();
      } else {
        arm();
        onChange();
        return;
      }
    }
    cancelTimer();
    st.attempt = 0;
    if (st.uploaded) {
      const n = st.uploaded;
      st.uploaded = 0;
      onDrained(n);
    }
  }

  // Sends every pending item, oldest first. `reset` (online, visible, Retry now, app start) drops
  // the backoff and any armed timer so the next attempt happens now.
  function flush({ reset = false } = {}) {
    if (st.running) return st.running;
    if (reset) {
      cancelTimer();
      st.attempt = 0;
    }
    if (st.paused) return Promise.resolve();
    if (st.timer != null) cancelTimer();
    st.running = Promise.resolve()
      .then(() => lock(run))
      .finally(() => { st.running = null; });
    return st.running;
  }

  return {
    async add(rec) {
      const clean = { state: "pending" };
      for (const k of FIELDS) clean[k] = rec[k];
      // ---- tags (spec §19): cleartext labels for the POST meta, kept only when there are some.
      if (Array.isArray(rec.tags) && rec.tags.length) clean.tags = [...rec.tags];
      // ---- tickets (spec T10): the sealed POST body, its ticket, and the file it waits for
      if (rec.kind === "ticket-event") {
        clean.ref = rec.ref;
        clean.body = rec.body;
        if (rec.after_uuid) clean.after_uuid = rec.after_uuid;
      }
      // ---- TIX on orch-core (Task 9): a sealed decision; a second add of the same uuid is a no-op
      if (rec.kind === "decision") {
        for (const k of ["space", "ticket", "decisionKind", "body"]) clean[k] = rec[k];
        for (const k of ["wrapped_dek", "enc_meta", "ttl", "blob"]) delete clean[k];
      }
      let added;
      try {
        added = await store.addChecked(clean, (items) => {
          const dup = rec.kind === "decision" ? items.find((x) => x.kind === "decision" && x.uuid === rec.uuid) : null;
          if (dup) throw new AlreadyQueued(dup.seq);
          checkLimits(items, rec.size || 0);
        });
      } catch (e) {
        if (e instanceof AlreadyQueued) return e.seq;
        throw e;
      }
      const { seq, before } = added;
      if (before === 0) {
        try { persist(); } catch { /* best effort */ }
      }
      onChange();
      return seq;
    },
    flush,
    // The first retry after a failed direct upload: in 5 s, not at once.
    schedule() {
      if (st.timer == null && !st.running) arm();
    },
    async resume() {
      st.paused = false;
      await flush({ reset: true });
    },
    async retry(seq) {
      const it = await store.get(seq);
      if (it) await store.put({ ...it, state: "pending", error: undefined });
      onChange();
      await this.resume();
    },
    // Replaces fields of one item and makes it pending again (the Tickets page's "Send without
    // the voice": a re-sealed body and no after_uuid).
    async update(seq, patch) {
      const it = await store.get(seq);
      if (it) await store.put({ ...it, ...patch, state: "pending", error: undefined });
      onChange();
    },
    async discard(seq) {
      await store.delete(seq);
      onChange();
    },
    async clear() {
      cancelTimer();
      await store.clear();
      onChange();
    },
    items: () => store.all(),
    async count() { return (await store.all()).length; },
    status: () => ({ paused: st.paused, nextRetryAt: st.nextRetryAt, flushing: Boolean(st.running) }),
  };
}
